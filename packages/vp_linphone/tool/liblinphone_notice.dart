// Generates the liblinphone section of the repository's NOTICE from the files
// the SDK release itself ships: the POM, the AAR (and every LICENSE, COPYING
// or NOTICE file inside it), and the sources jar. Nothing is taken from
// anywhere else: a component whose licence the SDK does not state is listed
// as "licence not stated in the SDK".
//
// Run from packages/vp_linphone on an upgrade:
//
//   dart run tool/liblinphone_notice.dart --version 5.5.39 --write ../../NOTICE
//
// Without --write it prints the section. --cache DIR keeps the downloads
// (default: a temporary directory, deleted afterwards). Each download is
// checked against the repository's own .sha256 file.

import 'dart:convert';
import 'dart:io';

import 'package:archive/archive.dart';
import 'package:crypto/crypto.dart';

const repo = 'https://download.linphone.org/maven_repository/org/linphone/linphone-sdk-android';
const begin = '[generated by packages/vp_linphone/tool/liblinphone_notice.dart; do not edit by hand]';
const end = '[end of the generated liblinphone section]';

/// Components looked for inside the native libraries, by symbol or string.
/// Detection only says the code is there; the licence column comes from the
/// SDK's own files or says it is not stated.
const components = <(String, String)>[
  ('liblinphone', r'linphone_core_new|linphone_core_start'),
  ('belle-sip', r'belle_sip_stack_new|belle_sip_'),
  ('belr', r'belr::|4belr'),
  ('bctoolbox', r'bctbx_'),
  ('oRTP', r'ortp_init|rtp_session_new'),
  ('mediastreamer2', r'ms_factory_new|ms_factory_'),
  ('bzrtp (ZRTP)', r'bzrtp_'),
  ('lime', r'lime::|4lime'),
  ('ML-KEM (post-quantum KEM)', r'MLKem|mlkem|ML-KEM|[Kk]yber'),
  ('mbedTLS', r'mbedtls_ssl_'),
  ('decaf (Ed448)', r'decaf_'),
  ('libsrtp', r'srtp_init|srtp_create'),
  ('opus', r'opus_encoder_create|libopus [0-9.]+'),
  ('speex', r'speex_resampler_init|speex_lib_get_mode|speex_echo_state_init'),
  ('GSM 06.10', r'gsm_create'),
  ('BroadVoice16', r'bv16_'),
  ('libvpx', r'vpx_codec_|libvpx'),
  ('aom', r'aom_codec_'),
  ('dav1d', r'dav1d_'),
  ('xerces-c', r'xercesc_3_[0-9]+'),
  ('libxml2', r'libxml2|xmlNewDoc|xmlReadMemory|xmlParseMemory'),
  ('soci', r'soci::'),
  ('SQLite', r'sqlite3_open'),
  ('zlib', r'inflateInit|deflateInit|Zlib'),
  ('OpenLDAP client', r'ldap_init|ldap_sasl_bind'),
  ('WebRTC audio processing', r'webrtc::|WebRtc'),
  ('libjpeg-turbo', r'libjpeg-turbo|tjInitCompress|jpeg_CreateDecompress'),
  ('jsoncpp', r'Json::'),
  ('ZXing-C++', r'ZXing'),
];

/// Licence-like statements in a binary's printable strings.
final licenceString = RegExp(
  r'[\x20-\x7e]{0,100}(?:[Cc]opyright|[Ll]icen[cs]e|GNU |[Pp]ublic domain|Permission is hereby|\(c\) [0-9])[\x20-\x7e]{0,120}',
);

Future<void> main(List<String> args) async {
  String opt(String name, String fallback) {
    final i = args.indexOf(name);
    return i >= 0 && i + 1 < args.length ? args[i + 1] : fallback;
  }

  final version = opt('--version', '5.5.39');
  final write = opt('--write', '');
  final cacheArg = opt('--cache', '');
  final cache = cacheArg.isEmpty ? await Directory.systemTemp.createTemp('liblinphone') : Directory(cacheArg);
  await cache.create(recursive: true);

  try {
    final name = 'linphone-sdk-android-$version';
    final pom = await fetch('$repo/$version/$name.pom', cache);
    final aar = await fetch('$repo/$version/$name.aar', cache);
    final sources = await fetch('$repo/$version/$name-sources.jar', cache);
    final section = build(version, pom, aar, sources);
    if (write.isEmpty) {
      stdout.write(section);
    } else {
      replaceSection(File(write), section);
      stderr.writeln('Wrote the liblinphone section of $write');
    }
  } finally {
    if (cacheArg.isEmpty) await cache.delete(recursive: true);
  }
}

Future<File> fetch(String url, Directory dir) async {
  final file = File('${dir.path}/${url.split('/').last}');
  if (!file.existsSync()) {
    final client = HttpClient();
    try {
      final res = await (await client.getUrl(Uri.parse(url))).close();
      if (res.statusCode != 200) throw StateError('$url: HTTP ${res.statusCode}');
      await res.pipe(file.openWrite());
    } finally {
      client.close();
    }
  }
  final expected = await fetchText('$url.sha256');
  final actual = sha256.convert(file.readAsBytesSync()).toString();
  if (expected.trim().split(RegExp(r'\s+')).first.toLowerCase() != actual) {
    throw StateError('${file.path}: SHA-256 $actual does not match the repository\'s .sha256');
  }
  return file;
}

Future<String> fetchText(String url) async {
  final client = HttpClient();
  try {
    final res = await (await client.getUrl(Uri.parse(url))).close();
    if (res.statusCode != 200) throw StateError('$url: HTTP ${res.statusCode}');
    return await res.transform(utf8.decoder).join();
  } finally {
    client.close();
  }
}

String build(String version, File pom, File aar, File sourcesJar) {
  final b = StringBuffer()
    ..writeln(begin)
    ..writeln('- liblinphone SDK for Android (org.linphone:linphone-sdk-android $version, from')
    ..writeln('  https://download.linphone.org/maven_repository), Belledonne Communications')
    ..writeln('  SARL. Used by packages/vp_linphone. Licences below are only as the SDK\'s')
    ..writeln('  own files state them; each names the file it comes from.');

  // POM.
  final pomText = pom.readAsStringSync();
  final licences = RegExp(
    r'<license>\s*<name>([^<]*)</name>\s*(?:<url>([^<]*)</url>)?',
    multiLine: true,
  ).allMatches(pomText).map((m) => '"${m[1]!.trim()}"${m[2] == null ? '' : ' (${m[2]!.trim()})'}').toList();
  b.writeln('  - The SDK as a whole: ${licences.isEmpty ? 'licence not stated in the SDK' : licences.join('; ')}');
  b.writeln('    [${pom.uri.pathSegments.last}, <licenses>]');

  // Licence files inside the AAR and the sources jar.
  final aarArchive = ZipDecoder().decodeBytes(aar.readAsBytesSync());
  final jarArchive = ZipDecoder().decodeBytes(sourcesJar.readAsBytesSync());
  final licenceFiles = [
    for (final (label, a) in [('AAR', aarArchive), ('sources jar', jarArchive)])
      for (final f in a.files)
        if (f.isFile && RegExp(r'(^|/)(LICEN[CS]E|COPYING|NOTICE)[^/]*$', caseSensitive: false).hasMatch(f.name))
          '$label: ${f.name}',
  ];
  b.writeln(
    '  - LICENSE, COPYING or NOTICE files in the AAR or the sources jar: '
    '${licenceFiles.isEmpty ? 'none' : licenceFiles.join(', ')}',
  );

  // Java sources: the licence header of each file.
  final headers = <String, List<String>>{};
  for (final f in jarArchive.files) {
    if (!f.isFile || !f.name.endsWith('.java')) continue;
    final head = utf8.decode(f.content as List<int>, allowMalformed: true).split('\n').take(40).join(' ');
    final kind = head.contains('GNU Affero General Public License') && head.contains('either version 3')
        ? 'GNU AGPL, version 3 or (at your option) any later version'
        : head.contains('GNU General Public License') && head.contains('either version 2')
        ? 'GNU GPL, version 2 or (at your option) any later version'
        : head.contains('GNU General Public License') && head.contains('version 3')
        ? 'GNU GPL, version 3'
        : 'no licence header';
    (headers[kind] ??= []).add(f.name);
  }
  b.writeln('  - Java API and Android classes (classes.jar), by each source file\'s header in');
  b.writeln('    ${sourcesJar.uri.pathSegments.last}:');
  for (final e in headers.entries) {
    final ex = (e.value..sort()).take(2).join(', ');
    b.writeln('    - ${e.key}: ${e.value.length} files, for example $ex');
  }

  // Bundled data.
  for (final f in aarArchive.files) {
    if (f.isFile && f.name.endsWith('rootca.pem')) {
      final head = utf8.decode(f.content as List<int>, allowMalformed: true).split('\n').take(20).join('\n');
      final stated = licenceString.firstMatch(head);
      b.writeln(
        '  - Root CA bundle (${f.name}): '
        '${stated == null ? 'licence not stated in the SDK' : '"${stated[0]!.trim()}"'}',
      );
    }
  }

  // Native libraries.
  final so = aarArchive.files.where((f) => f.isFile && f.name.startsWith('jni/') && f.name.endsWith('.so')).toList();
  final abis = so.map((f) => f.name.split('/')[1]).toSet().toList()..sort();
  final libNames = so.map((f) => f.name.split('/').last).toSet().toList()..sort();
  b.writeln('  - Native libraries in jni/ (${abis.join(', ')}): ${libNames.join(', ')}.');
  b.writeln('    None of them ships a licence text; licence-like strings found in them are');
  b.writeln('    quoted below with their file. Components named in them (by symbol or');
  b.writeln('    string, so a library that only calls a component lists it too):');
  final reference = abis.contains('arm64-v8a') ? 'arm64-v8a' : abis.first;
  final found = <String, Set<String>>{};
  final statements = <String, Set<String>>{};
  for (final f in so.where((f) => f.name.split('/')[1] == reference)) {
    final text = latin1.decode(f.content as List<int>);
    final lib = f.name.split('/').last;
    for (final (component, pattern) in components) {
      if (RegExp(pattern).hasMatch(text)) (found[component] ??= <String>{}).add(lib);
    }
    if (lib == 'libc++_shared.so') (found['LLVM libc++'] ??= <String>{}).add(lib);
    for (final m in licenceString.allMatches(text)) {
      final s = m[0]!.trim();
      if (RegExp(r'[A-Za-z]{4,} [A-Za-z]{2,}').hasMatch(s)) (statements[lib] ??= <String>{}).add(s);
    }
  }
  for (final component in [for (final (c, _) in components) c, 'LLVM libc++']) {
    final libs = found[component];
    if (libs == null) continue;
    final quoted = [
      for (final lib in libs)
        for (final s in statements[lib] ?? const <String>{})
          if (s.toLowerCase().contains(component.split(' ').first.toLowerCase())) '"$s" (jni/$reference/$lib)',
    ];
    b.writeln(
      '    - $component (in ${(libs.toList()..sort()).join(', ')}): licence not stated in the SDK'
      '${quoted.isEmpty ? '' : '; the only statement is ${quoted.join('; ')}'}',
    );
  }
  b.writeln(end);
  return b.toString();
}

void replaceSection(File notice, String section) {
  final text = notice.readAsStringSync();
  final start = text.indexOf(begin);
  final stop = text.indexOf(end);
  if (start < 0 || stop < start) throw StateError('${notice.path}: generated-section markers not found');
  notice.writeAsStringSync(text.substring(0, start) + section + text.substring(stop + end.length + 1));
}
